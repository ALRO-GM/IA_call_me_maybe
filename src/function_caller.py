"""The pipeline that turns one request into one function call."""

import json
from typing import Any, Dict, List, Optional, Tuple

from pydantic import BaseModel, PrivateAttr

from src.decoder import ConstrainedDecoder, DecodingStep
from src.grammar import Grammar, arguments_grammar, function_name_grammar
from src.io_utils import warn
from src.models import FunctionCall, FunctionDefinition
from src.prompt_builder import PromptBuilder


class CallTrace(BaseModel):
    """Details of how one function call was produced.

    Attributes:
        raw_json: The exact text generated by the model.
        steps: Decoding steps (empty unless the decoder traces).
        model_calls: Number of forward passes used.
        generated_tokens: Number of tokens in the answer.
    """

    raw_json: str
    steps: List[DecodingStep] = []
    model_calls: int = 0
    generated_tokens: int = 0


class FunctionCaller(BaseModel):
    """Selects a function and its arguments for a natural language request.

    The answer is one JSON object generated in two constrained stages:

    1. ``{"name": "<function>"`` where the name is restricted to the known
       functions. This is where the model chooses the function, reading a
       prompt that lists all of them.
    2. ``, "parameters": {...}}`` following the schema of that function,
       reading a shorter prompt that only describes the chosen function.

    Attributes:
        functions: The functions the model can choose from.
        prompt_builder: Builds the model input for a request.
        decoder: Constrained decoder driving the model.
        fallback_decoder: Decoder with stricter limits, tried when the
            first one cannot finish an answer.
    """

    functions: List[FunctionDefinition]
    prompt_builder: PromptBuilder
    decoder: ConstrainedDecoder
    fallback_decoder: Optional[ConstrainedDecoder] = None

    _name_grammar: Grammar = PrivateAttr()
    _by_name: Dict[str, FunctionDefinition] = PrivateAttr(
        default_factory=dict
    )
    _argument_grammars: Dict[str, Grammar] = PrivateAttr(
        default_factory=dict
    )

    def model_post_init(self, context: Any) -> None:
        """Compile the grammar that selects a function.

        Args:
            context: Unused pydantic validation context.
        """
        if not self.functions:
            raise ValueError("at least one function is required")
        self._by_name = {
            function.name: function for function in self.functions
        }
        self._name_grammar = function_name_grammar(list(self._by_name))

    def _generate(
        self, prompt: str, decoder: ConstrainedDecoder
    ) -> Tuple[FunctionCall, CallTrace]:
        """Run the two decoding stages with a given decoder.

        Args:
            prompt: The natural language request.
            decoder: Decoder to use for both stages.

        Returns:
            The function call and a trace of its generation.

        Raises:
            RuntimeError: If the generation cannot be completed.
            ValueError: If the generated JSON fails the final validation.
        """
        selection = self.prompt_builder.selection_prompt(prompt)
        chosen = decoder.generate(selection, self._name_grammar)
        name = json.loads(chosen.data + b"}")["name"]
        function = self._by_name[name]
        grammar = self._argument_grammars.get(name)
        if grammar is None:
            grammar = arguments_grammar(function)
            self._argument_grammars[name] = grammar
        context = self.prompt_builder.arguments_prompt(prompt, function)
        arguments = decoder.generate(context + chosen.token_ids, grammar)
        raw = (chosen.data + arguments.data).decode("utf-8")
        # Independent check: the text must parse and match the schema.
        parameters = function.coerce_arguments(json.loads(raw)["parameters"])
        call = FunctionCall(prompt=prompt, name=name, parameters=parameters)
        trace = CallTrace(
            raw_json=raw,
            steps=chosen.steps + arguments.steps,
            model_calls=chosen.model_calls + arguments.model_calls,
            generated_tokens=len(chosen.token_ids)
            + len(arguments.token_ids),
        )
        return call, trace

    def call(self, prompt: str) -> Tuple[FunctionCall, CallTrace]:
        """Translate a request into a function call.

        If the main decoder fails (for instance an answer longer than its
        token budget), the fallback decoder is tried before giving up.

        Args:
            prompt: The natural language request.

        Returns:
            The function call and a trace of its generation.

        Raises:
            RuntimeError: If every attempt failed.
        """
        decoders = [self.decoder]
        if self.fallback_decoder is not None:
            decoders.append(self.fallback_decoder)
        problems: List[str] = []
        for decoder in decoders:
            try:
                return self._generate(prompt, decoder)
            except (RuntimeError, ValueError, KeyError, IndexError) as error:
                problems.append(f"{type(error).__name__}: {error}")
                if len(problems) < len(decoders):
                    warn(f"{problems[-1]}; retrying with stricter limits")
        raise RuntimeError("; ".join(problems))
